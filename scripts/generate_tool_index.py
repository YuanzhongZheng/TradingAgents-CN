"""Generate the lazy tool index without importing SDKs.

Run from the repository root: python scripts/generate_tool_index.py [--check]
The checked-in Python index also works in source-protected, pyc-only deployments.
Metadata remains defined by the existing decorators, not duplicated here.
"""
import ast
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "core/tools/_tool_index.py"


def render():
    index = {}
    for path in sorted((ROOT / "core/tools/implementations").rglob("*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                continue
            for decorator in node.decorator_list:
                if not (isinstance(decorator, ast.Call)
                        and isinstance(decorator.func, ast.Name)
                        and decorator.func.id == "register_tool"):
                    continue
                keywords = {kw.arg: kw.value for kw in decorator.keywords}
                if ast.literal_eval(keywords.get("auto_register", ast.Constant(True))) is False:
                    continue
                tool_id = ast.literal_eval(keywords["tool_id"])
                module = ".".join(path.relative_to(ROOT).with_suffix("").parts)
                if tool_id in index:
                    raise ValueError(f"Duplicate tool ID: {tool_id}")
                index[tool_id] = module
    lines = [
        '"""Generated by scripts/generate_tool_index.py; do not edit by hand."""',
        "", "TOOL_MODULES = {",
    ]
    lines += [f"    {key!r}: {value!r}," for key, value in sorted(index.items())]
    return "\n".join([*lines, "}", ""])


if __name__ == "__main__":
    content = render()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != content:
            raise SystemExit("Tool index is stale; run python scripts/generate_tool_index.py")
    else:
        TARGET.write_text(content, encoding="utf-8")
